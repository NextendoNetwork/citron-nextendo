// Validate every record before writing any: reject conflicting mods, wrong images and
// nonzero executable padding; accept the exact reviewed patch again (idempotent).
inline bool Apply(uint64_t title, std::string_view build, std::string_view module,
                  std::span<uint8_t> program) {
    if (title != 0x0100EA6014BB8000ULL || module != "main")
        return false;
    std::span<const Record> records;
    if (build == "E63D7A75EE916F07C9AAC2985A9F5CFC3114456A000000000000000000000000")
        records = kBuild0;
    if (build == "ED8426574258F6728BE883C22010730D5D6DB531000000000000000000000000")
        records = kBuild1;
    if (records.empty())
        return false;
    for (const auto& r : records) {
        if (r.offset > program.size() || r.data.size() > program.size() - r.offset)
            return false;
        const auto current = program.subspan(r.offset, r.data.size());
        if (std::equal(current.begin(), current.end(), r.data.begin()))
            continue;
        if (r.original.empty()) {
            if (!std::all_of(current.begin(), current.end(), [](auto b) { return b == 0; }))
                return false;
        } else if (!std::equal(current.begin(), current.end(), r.original.begin()))
            return false;
    }
    for (const auto& r : records)
        std::copy(r.data.begin(), r.data.end(), program.begin() + r.offset);
    return true;
}
