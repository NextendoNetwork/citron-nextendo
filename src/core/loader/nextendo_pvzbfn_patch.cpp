std::vector<u8> ApplyIfMatch(u64 title_id, const std::array<u8, 0x20>& build_id,
                             std::vector<u8> nso) {
    if (title_id != kTitleId) {
        return nso;
    }
    const auto build_id_raw = Common::HexToString(build_id);
    const auto trimmed = build_id_raw.substr(0, build_id_raw.find_last_not_of('0') + 1);
    const auto build = std::find_if(kBuilds.begin(), kBuilds.end(),
                                    [&](const Build& b) { return b.build_id == trimmed; });
    if (build == kBuilds.end()) {
        return nso;
    }
    const std::size_t offset = kNsoHeaderSize + build->modulus_offset;
    if (nso.size() < offset + kNextendoModulus.size() ||
        !std::equal(kEaModulusPrefix.begin(), kEaModulusPrefix.end(), nso.begin() + offset)) {
        LOG_ERROR(Loader, "[Nextendo] PvZ BfN: CA entry not found, trust patch skipped");
        return nso;
    }
    std::memcpy(nso.data() + offset, kNextendoModulus.data(), kNextendoModulus.size());
    LOG_INFO(Loader, "[Nextendo] PvZ BfN: built-in CA trust patch applied");
    return nso;
}

