std::vector<u8> ApplyIfMatch(u64 title_id, const std::array<u8, 0x20>& build_id,
                             std::vector<u8> nso) {
    if (title_id != kTitleId) {
        return nso;
    }
    const auto build_id_raw = Common::HexToString(build_id);
    if (build_id_raw.substr(0, build_id_raw.find_last_not_of('0') + 1) != kBuildId) {
        return nso;
    }
    auto in_file = std::make_shared<FileSys::VectorVfsFile>(nso, "nso");
    const auto patch = std::make_shared<FileSys::VectorVfsFile>(
        std::vector<u8>(kHostPatch.begin(), kHostPatch.end()), "dungeons2_host.ips32");
    const auto patched = FileSys::PatchIPS(in_file, patch);
    if (patched == nullptr) {
        LOG_ERROR(Loader, "[Nextendo] Dungeons II: built-in host patch failed to apply");
        return nso;
    }
    LOG_INFO(Loader, "[Nextendo] Dungeons II: built-in host patch applied");
    return patched->ReadAllBytes();
}

